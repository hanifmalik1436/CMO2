/** The icon for how a source came in. */
export function kindIcon(kind: string): IconName {
  switch (kind) {
    case 'RECORDING': return 'mic'
    case 'UPLOAD': return 'upload'
    case 'LINK': return 'link'
    case 'NOTES': return 'pen'
    default: return 'paste'
  }
}
