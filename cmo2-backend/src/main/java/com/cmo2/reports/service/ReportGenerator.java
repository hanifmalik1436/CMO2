package com.cmo2.reports.service;

import com.lowagie.text.Document;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import org.springframework.stereotype.Component;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.util.List;

/**
 * Renders a leadership KPI report to PDF bytes using OpenPDF. Pure rendering — no
 * persistence, no security, no data access — so it is trivially testable and reusable by
 * both the on-demand and scheduled paths.
 */
@Component
public class ReportGenerator {

    /** A single labelled metric line in the KPI table. */
    public record KpiRow(String label, String value) {}

    private static final Color BRAND = new Color(0x4F, 0x46, 0xE5);   // indigo
    private static final Color HEADER_TEXT = Color.WHITE;
    private static final Color MUTED = new Color(0x6B, 0x72, 0x80);

    public byte[] render(String title, String subtitle, String period, List<KpiRow> rows) {
        Document doc = new Document(PageSize.A4, 48, 48, 54, 54);
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        PdfWriter.getInstance(doc, out);
        doc.open();
        try {
            Font titleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 22, BRAND);
            Font subFont = FontFactory.getFont(FontFactory.HELVETICA, 12, MUTED);
            Font metaFont = FontFactory.getFont(FontFactory.HELVETICA, 9, MUTED);

            Paragraph heading = new Paragraph(title, titleFont);
            heading.setSpacingAfter(4);
            doc.add(heading);

            if (subtitle != null && !subtitle.isBlank()) {
                doc.add(new Paragraph(subtitle, subFont));
            }
            if (period != null && !period.isBlank()) {
                Paragraph p = new Paragraph("Reporting period: " + period, metaFont);
                p.setSpacingAfter(16);
                doc.add(p);
            } else {
                doc.add(new Paragraph(" ", metaFont));
            }

            doc.add(buildTable(rows));

            Paragraph footer = new Paragraph(
                    "Generated by CMO² — the self-improving marketing command platform.",
                    FontFactory.getFont(FontFactory.HELVETICA_OBLIQUE, 9, MUTED));
            footer.setSpacingBefore(24);
            doc.add(footer);
        } finally {
            doc.close();
        }
        return out.toByteArray();
    }

    private PdfPTable buildTable(List<KpiRow> rows) {
        PdfPTable table = new PdfPTable(2);
        table.setWidthPercentage(100);
        try {
            table.setWidths(new float[] {3f, 2f});
        } catch (Exception ignored) {
            // fixed widths are best-effort; default layout is fine
        }

        table.addCell(headerCell("Metric"));
        table.addCell(headerCell("Value"));

        Font cellFont = FontFactory.getFont(FontFactory.HELVETICA, 11, Color.DARK_GRAY);
        boolean zebra = false;
        for (KpiRow row : rows) {
            table.addCell(bodyCell(row.label(), cellFont, zebra));
            table.addCell(bodyCell(row.value(), cellFont, zebra));
            zebra = !zebra;
        }
        return table;
    }

    private PdfPCell headerCell(String text) {
        Font font = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 11, HEADER_TEXT);
        PdfPCell cell = new PdfPCell(new Phrase(text, font));
        cell.setBackgroundColor(BRAND);
        cell.setPadding(8);
        cell.setBorderColor(BRAND);
        return cell;
    }

    private PdfPCell bodyCell(String text, Font font, boolean zebra) {
        PdfPCell cell = new PdfPCell(new Phrase(text == null ? "—" : text, font));
        cell.setPadding(7);
        cell.setBorderColor(new Color(0xE5, 0xE7, 0xEB));
        if (zebra) {
            cell.setBackgroundColor(new Color(0xF9, 0xFA, 0xFB));
        }
        cell.setHorizontalAlignment(Element.ALIGN_LEFT);
        return cell;
    }
}
